import { expect, test } from '@playwright/test'

test('a selected B737 review retains aircraft-family qualification checks', async ({ page }) => {
  await page.setViewportSize({ width: 820, height: 1180 })
  await page.goto('/fleet/N811QX/swaps/N742AX?hours=2&record=BX210')
  await expect(page.getByLabel('Selected record context')).toContainText('BX210')
  await page.getByRole('button', { name: 'Claim release review' }).click()
  await expect(page.getByRole('status')).toContainText('aircraft-family')
  await page.screenshot({ path: '../UI_SCREENSHOTS/fifteenth-AeroFleet-detail.png', fullPage: true })
})

test('detail release and workspace share one record with durable history', async ({ page }) => {
  await page.goto('/fleet/release-workspace?flight=AX417')
  await page.getByRole('link', { name: 'Open record details' }).click()
  await expect(page.getByLabel('Selected record context')).toContainText('AX417')
  await page.getByLabel('Engineering signature present').check()
  await page.getByLabel('Authority').selectOption('approver')
  await page.getByLabel('Release rationale').fill('Engineering evidence verified for this selected flight.')
  await page.getByRole('button', { name: 'Record return to service' }).click()
  await expect(page.getByRole('status')).toContainText('release recorded')
  await page.getByRole('link', { name: 'Back to workspace' }).click()
  await expect(page.getByLabel('Selected flight')).toContainText('2026-09-16')
  await page.reload()
  await expect(page.getByLabel('Selected flight')).toContainText('2026-09-16')
  await page.getByRole('link', { name: 'Open record details' }).click()
  await expect(page.getByText('Durable release:')).toContainText('2026-09-16')
})

test('a concurrent edit is recoverable and does not clear the local rationale', async ({ page }) => {
  await page.goto('/fleet/N742AX/availability?record=AX417')
  await page.getByLabel('Engineering signature present').check()
  await page.getByLabel('Authority').selectOption('approver')
  await page.getByLabel('Release rationale').fill('Preserve this draft while reviewing a concurrent release.')
  const other = await page.context().newPage()
  await other.goto('/fleet/N742AX/availability?record=AX417')
  await other.getByLabel('Engineering signature present').check()
  await other.getByLabel('Authority').selectOption('approver')
  await other.getByLabel('Release rationale').fill('Release approved in another review window.')
  await other.getByRole('button', { name: 'Record return to service' }).click()
  await page.getByRole('button', { name: 'Record return to service' }).click()
  await expect(page.getByRole('alert')).toContainText('changed in another view')
  await expect(page.getByLabel('Release rationale')).toHaveValue('Preserve this draft while reviewing a concurrent release.')
  await page.getByRole('button', { name: 'Reload record and discard local edits' }).click()
  await expect(page.getByLabel('Selected record context')).toBeFocused()
  await expect(page.getByText('Durable release:')).toContainText('2026-09-16')
  await other.close()
})

test('unknown record routes provide recovery instead of opening the default flight', async ({ page }) => {
  await page.goto('/fleet/N742AX/availability?record=MISSING')
  await expect(page.getByRole('alert')).toContainText('not found')
  await expect(page.getByRole('button', { name: 'Record return to service' })).toHaveCount(0)
  await page.getByRole('link', { name: 'Back to workspace' }).click()
  await expect(page.getByRole('heading', { name: 'Flight release workspace' })).toBeVisible()
})
