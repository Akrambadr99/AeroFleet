import { expect, test } from '@playwright/test'

test('flight triage URL and selected detail survive reload and a detail round trip', async ({ page }) => {
  await page.goto('/fleet/release-workspace?flight=AX418&q=A320&state=review-unclaimed&sort=revision-desc&show=all&size=5')
  await expect(page.getByLabel('Search flights')).toHaveValue('A320')
  await expect(page.getByLabel('Work state')).toHaveValue('review-unclaimed')
  await page.reload()
  await expect(page.getByLabel('Sort flights')).toHaveValue('revision-desc')
  await page.getByRole('link', { name: 'Open record details' }).click()
  await page.getByRole('link', { name: 'Back to workspace' }).click()
  await expect(page.getByLabel('Search flights')).toHaveValue('A320')
  await expect(page.getByLabel('Work state')).toHaveValue('review-unclaimed')
  await expect(page.getByLabel('Selected flight', { exact: true })).toContainText('AX418')
  await page.getByRole('link', { name: 'Open decision workflow' }).click()
  await page.getByRole('link', { name: 'Back to workspace' }).click()
  await expect(page.getByLabel('Search flights')).toHaveValue('A320')
  await expect(page.getByLabel('Work state', { exact: true })).toHaveValue('review-unclaimed')
})
test('page selection stays explicit across filtering and empty-state recovery', async ({ page }) => {
  await page.setViewportSize({ width: 820, height: 1180 })
  await page.goto('/fleet/release-workspace?flight=AX418&show=all&size=5')
  await page.getByRole('button', { name: 'Select this page' }).click()
  await page.getByRole('button', { name: 'Next page' }).click()
  await expect(page.getByRole('group', { name: 'Bulk selection' })).toContainText('5 flights selected · 5 outside this page')
  await page.getByRole('button', { name: 'Select this page' }).click()
  await page.getByLabel('Search flights').fill('no-match')
  await expect(page.getByRole('group', { name: 'Bulk selection' })).toContainText('6 flights selected · 6 outside this page')
  await expect(page.getByLabel('Selected flight', { exact: true })).toContainText('AX418')
  await page.getByRole('button', { name: 'Reset view' }).click()
  await expect(page.getByRole('group', { name: 'Bulk selection' })).toContainText('6 flights selected · 1 outside this page')
  await page.screenshot({ path: '../UI_SCREENSHOTS/sixteenth-AeroFleet-triage.png', fullPage: true })
  await page.getByRole('button', { name: 'Clear selection' }).click()
  await expect(page.getByRole('button', { name: 'Revalidate selected swaps' })).toBeDisabled()
})
test('deliberate filter changes participate in browser history', async ({ page }) => {
  await page.goto('/fleet/release-workspace?flight=AX418')
  await page.getByLabel('Show', { exact: true }).selectOption('all')
  await page.getByLabel('Sort flights').selectOption('id-desc')
  await page.goBack()
  await expect(page.getByLabel('Sort flights')).toHaveValue('id-asc')
  await expect(page.getByLabel('Show', { exact: true })).toHaveValue('all')
  await page.goBack()
  await expect(page.getByLabel('Show', { exact: true })).toHaveValue('active')
  await page.goForward()
  await expect(page.getByLabel('Show', { exact: true })).toHaveValue('all')
})

test('a qualified claim moves the flight out of unclaimed triage without replacing selection', async ({ page }) => {
  await page.goto('/fleet/release-workspace?flight=AX418&state=review-unclaimed')
  await page.getByRole('button', { name: 'Claim selected review', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Review claimed')
  await expect(page.getByLabel('Flight collection', { exact: true }).getByRole('button', { name: /^AX418 ·/ })).toHaveCount(0)
  await expect(page.getByLabel('Selected flight', { exact: true })).toContainText('AX418')
  await page.getByRole('button', { name: 'Show selected record' }).click()
  await expect(page.getByLabel('Search flights')).toHaveValue('AX418')
  await expect(page.getByLabel('Flight collection', { exact: true })).toContainText('Inspection review assigned')
  await page.reload()
  await expect(page.getByLabel('Flight collection', { exact: true })).toContainText('Inspection review assigned')
})
